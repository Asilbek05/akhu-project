                            <p class="pt-2">Front-end engineer - they design, develop, build, and maintain user interfaces (UI) using common programming languages such as JavaScript and CSS</p>
                            <p class="pt-2">Back-end engineer – they write server-side scripts and application programming interfaces (APIs) that ensure the functionality of websites and applications. Daily tasks include server optimization, security, and data handling</p>
                            <p class="pt-2">Full-stack engineer - they possess the technical skills of both front-end and back-end engineers. As such, they handle both client-side and server-side responsibilities</p>
                            <p class="pt-2">Quality assurance (QA) engineer – they are responsible for analyzing software and identifying any issues, bugs, or errors. They are involved in virtually every phase of the software development life cycle, ensuring the software meets all company requirements and validating the final product</p>
                            <p class="pt-2">Data engineer - their primary responsibility is to convert raw data into information that is easily accessed and analyzed. To achieve this goal, date engineers develop software systems that can compile, manage, and transform data into actionable information</p>
                            <p class="pt-2">DevOps engineer - they utilize their proficiencies in programming and engineering to create systems, tools, and methodologies designed to improve technologies used within a company.</p>
